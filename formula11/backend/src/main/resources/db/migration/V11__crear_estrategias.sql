CREATE TABLE estrategia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    version INTEGER NOT NULL,
    pesos JSONB NOT NULL,
